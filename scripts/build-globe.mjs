// Builds src/components/globe/globe-dots.ts — land as dots on a sphere, for the 3D hero globe.
// Fibonacci-sphere sampling (even spacing), kept when the point falls on land (Natural Earth 1:110m).
// kind: 0 = rest of the world, 1 = Africa, 2 = Togo.
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const load = (f) => JSON.parse(readFileSync(require.resolve(`world-atlas/${f}`), "utf8"));
const topo = load("countries-110m.json");
const fine = load("countries-50m.json");
const AFRICA = new Set([12,24,72,108,120,140,148,174,178,180,204,226,231,232,262,266,270,288,324,384,404,426,430,434,450,454,466,478,480,504,508,516,562,566,624,646,686,694,706,710,716,728,729,732,748,768,788,800,818,834,854,894,132,678]);
const countries = feature(topo, topo.objects.countries).features;
const africa = countries.filter((f) => AFRICA.has(Number(f.id)));
const others = countries.filter((f) => !AFRICA.has(Number(f.id)));
const togo = feature(fine, fine.objects.countries).features.find((f) => f.id === "768");

const N = 16000;
const out = [];
const golden = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = ((((i * golden) % (2 * Math.PI)) * 180) / Math.PI) - 180;
  const p = [lon, lat];
  let kind = -1;
  if (africa.some((f) => geoContains(f, p))) kind = geoContains(togo, p) ? 2 : 1;
  else if (others.some((f) => geoContains(f, p))) kind = 0;
  if (kind >= 0) out.push(+lat.toFixed(2), +lon.toFixed(2), kind);
}
// Togo is narrow: add a few extra dots inside it so it reads as a lit country.
for (let lat = 6.2; lat <= 11; lat += 0.45) for (let lon = -0.1; lon <= 1.7; lon += 0.4) if (geoContains(togo, [lon, lat])) out.push(+lat.toFixed(2), +lon.toFixed(2), 2);

const file = `// GENERATED by scripts/build-globe.mjs — do not edit by hand.
// Source: Natural Earth 1:110m via world-atlas@2.0.2. Flat list: lat, lon, kind (0 world, 1 Africa, 2 Togo).
export const DOTS = new Float32Array(${JSON.stringify(out)});
`;
mkdirSync(new URL("../src/components/globe/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/components/globe/globe-dots.ts", import.meta.url), file);
console.log("globe-dots.ts", out.length / 3, "dots,", (file.length / 1024).toFixed(0), "KB");
