// Builds src/components/map/africa-geo.ts from Natural Earth (world-atlas).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoMercator, geoPath } from "d3-geo";
import { feature, merge } from "topojson-client";

const require = createRequire(import.meta.url);
const load = (f) => JSON.parse(readFileSync(require.resolve(`world-atlas/${f}`), "utf8"));
// Continent + borders at 1:110m (light), Togo at 1:50m (its true narrow shape).
const topo = load("countries-110m.json");
const fine = load("countries-50m.json");

// ISO 3166 numeric codes of African countries (mainland + Madagascar).
const AFRICA = new Set([12,24,72,108,120,140,148,174,178,180,204,226,231,232,262,266,270,288,324,384,404,426,430,434,450,454,466,478,480,504,508,516,562,566,624,646,686,694,706,710,716,728,729,732,748,768,788,800,818,834,854,894,132,678]);
const TOGO = "768";

const geoms = topo.objects.countries.geometries.filter((g) => AFRICA.has(Number(g.id)));
const countries = feature(topo, { type: "GeometryCollection", geometries: geoms });
const W = 600, H = 640;
const projection = geoMercator().fitExtent([[20, 20], [W - 20, H - 20]], countries);
const path = geoPath(projection).digits(1);

const continent = path(merge(topo, geoms));
const borders = countries.features.filter((f) => f.id !== TOGO).map((f) => path(f)).join("");
const fineTogo = feature(fine, fine.objects.countries).features.find((f) => f.id === TOGO);
const togo = path(fineTogo);

const city = (name, lon, lat) => { const [x, y] = projection([lon, lat]); return { name, x: +x.toFixed(1), y: +y.toFixed(1) }; };
const lome = city("Lomé", 1.2123, 6.1375);
const cities = [
  city("Dakar", -17.4467, 14.6928), city("Abidjan", -4.0083, 5.36), city("Accra", -0.187, 5.6037),
  city("Lagos", 3.3792, 6.5244), city("Douala", 9.7043, 4.0511), city("Kinshasa", 15.2663, -4.4419),
  city("Nairobi", 36.8219, -1.2921), city("Johannesburg", 28.0473, -26.2041), city("Cairo", 31.2357, 30.0444),
  city("Casablanca", -7.5898, 33.5731), city("Addis Ababa", 38.7578, 8.9806), city("Cotonou", 2.3912, 6.3703),
];

const out = `// GENERATED by scripts/build-africa-map.mjs — do not edit by hand.
// Source: Natural Earth 1:110m (Togo 1:50m) via world-atlas@2.0.2, Mercator projection.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const CONTINENT = ${JSON.stringify(continent)};
export const BORDERS = ${JSON.stringify(borders)};
export const TOGO = ${JSON.stringify(togo)};
export const LOME = ${JSON.stringify(lome)};
export const CITIES = ${JSON.stringify(cities)};
`;
writeFileSync(new URL("../src/components/map/africa-geo.ts", import.meta.url), out);
console.log("africa-geo.ts", (out.length / 1024).toFixed(0), "KB; Lomé", lome);
